export type TextKey = keyof typeof dict

export function tr(key: TextKey, lang: Lang): string {
  return dict[key][lang === 'zh' ? 0 : 1]
}

export function tf(key: TextKey, lang: Lang, ...args: (string | number)[]): string {
  return tr(key, lang).replace(/\{(\d+)\}/g, (_, i) => String(args[Number(i)] ?? ''))
}
